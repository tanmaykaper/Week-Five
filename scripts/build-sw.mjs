// Writes out/sw.js after `next build`: precaches every exported file so the app works
// offline after the first visit. Plain JS, no bundler, no third-party runtime.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const OUT = "out";
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
const SKIP = [/^sw\.js$/, /\.map$/, /^404\/?/, /^dev\//];

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])));
  return files.flat();
}

const files = (await walk(OUT)).map((f) => relative(OUT, f).split(sep).join("/")).filter((f) => !SKIP.some((r) => r.test(f)));
const hash = createHash("sha256");
for (const f of files.sort()) hash.update(f).update(await readFile(join(OUT, f)));
const version = hash.digest("hex").slice(0, 12);

// Directory pages are served at their folder URL ("/home/"), so cache them by that URL.
const urls = files.map((f) => `${base}/${f.endsWith("index.html") ? f.slice(0, -"index.html".length) : f}`);

const sw = `/* Week Five offline cache, generated by scripts/build-sw.mjs. Version ${version}. */
const CACHE = "weekfive-${version}";
const PRECACHE = ${JSON.stringify(urls)};
const BASE = ${JSON.stringify(base)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("weekfive-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// A reminder tapped while the app is in the background opens the page it is about.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const href = (event.notification.data && event.notification.data.href) || BASE + "/home/";
  event.waitUntil((async () => {
    const all = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
    const open = all.find((c) => new URL(c.url).origin === self.location.origin);
    if (open) { await open.focus(); return open.navigate(href); }
    return self.clients.openWindow(href);
  })());
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Navigations: the page's folder URL, with or without the trailing slash.
    if (req.mode === "navigate") {
      const path = url.pathname.endsWith("/") ? url.pathname : url.pathname + "/";
      const hit = (await cache.match(path)) || (await cache.match(url.pathname));
      if (hit) return hit;
      try { return await fetch(req); } catch { return (await cache.match(BASE + "/404.html")) || (await cache.match(BASE + "/")); }
    }
    // Assets and the router's payload files: cache first, ignoring cache-busting query strings.
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok && res.type === "basic") cache.put(req, res.clone());
      return res;
    } catch {
      return Response.error();
    }
  })());
});
`;
await writeFile(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached, version ${version}`);
